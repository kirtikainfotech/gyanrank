                            <tr>
                                <td><span class="gr-cell-title"><?= h($chapter['course_title']); ?></span><span class="gr-cell-subtitle">Course #<?= (int) $chapter['course_id']; ?></span></td>
                                <td><span class="gr-cell-title"><?= h($chapter['content_title']); ?></span><span class="gr-cell-subtitle">Chapter #<?= (int) $chapter['id']; ?></span></td>
                                <td><span class="badge bg-primary-transparent text-primary"><?= h(ucfirst((string) $chapter['content_type'])); ?></span></td>
