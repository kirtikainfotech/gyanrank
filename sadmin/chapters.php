$pageTitle = 'Chapters';
$pageSubtitle = 'All course chapters and content items generated by instructors.';
$activePage = 'chapters';

$perPageOptions = [10, 25, 50];
$perPage = (int) ($_GET['per_page'] ?? 10);
if (!in_array($perPage, $perPageOptions, true)) {
    $perPage = 10;
}
$page = max(1, (int) ($_GET['page'] ?? 1));
$summary = db()->query("
    SELECT COUNT(*) total,
           SUM(cc.status = 'published') published,
           SUM(cc.status <> 'published') draft,
           COUNT(DISTINCT cc.course_id) courses
    FROM instructor_course_contents cc
")->fetch_assoc() ?: [];
$totalRows = (int) ($summary['total'] ?? 0);
$publishedRows = (int) ($summary['published'] ?? 0);
$draftRows = (int) ($summary['draft'] ?? 0);
$courseRows = (int) ($summary['courses'] ?? 0);
$totalPages = max(1, (int) ceil($totalRows / $perPage));
if ($page > $totalPages) {
    $page = $totalPages;
}
$offset = ($page - 1) * $perPage;

$chapterStmt = db()->prepare("
    SELECT cc.id,
           cc.content_title,
           cc.content_type,
           cc.duration_minutes,
           cc.sort_order,
           cc.status,
           c.title AS course_title,
           u.full_name AS instructor_name,
           c.id AS course_id
    FROM instructor_course_contents cc
    INNER JOIN instructor_courses c ON c.id = cc.course_id
    LEFT JOIN users u ON u.id = cc.instructor_id
    ORDER BY c.title ASC, cc.sort_order ASC
    LIMIT ? OFFSET ?
");
$chapterStmt->bind_param('ii', $perPage, $offset);
$chapterStmt->execute();
$chapters = $chapterStmt->get_result()->fetch_all(MYSQLI_ASSOC);
$pageStart = $totalRows > 0 ? $offset + 1 : 0;
$pageEnd = min($offset + $perPage, $totalRows);
